// 🧑 "Also need simple ways to fully uninstall itself, perhaps a ltxp command"
//! `ltxp uninstall`: removes everything `install.sh` installed or edited, as recorded in its
//! manifest, after showing the list and asking once.
use std::io::{BufRead, IsTerminal, Write};
use std::path::PathBuf;
use std::process::Command;

const SPEC_HEADER: &str = "-- Generated by the ltxp installer.";

enum Step {
    /// file or directory to delete
    Path(PathBuf),
    /// exact line to drop from a file (the Emacs loader)
    Line(PathBuf, String),
    /// `code` or `codium` whose ltxp extension to uninstall
    Vscode(String),
}

fn describe(step: &Step) -> String {
    match step {
        Step::Path(p) => format!("delete {}", p.display()),
        Step::Line(f, l) => format!("remove line `{l}` from {}", f.display()),
        Step::Vscode(e) => format!("uninstall the ltxp extension from {e}"),
    }
}

fn home() -> PathBuf {
    std::env::var_os("HOME").map_or_else(|| PathBuf::from("/"), PathBuf::from)
}

/// Steps from the installer's manifest, plus this binary and its module, which are always
/// removed; installs from before the manifest existed get the default locations.
fn steps() -> Vec<Step> {
    let data = home().join(".local/share/ltxp");
    let manifest = std::fs::read_to_string(data.join("manifest")).unwrap_or_default();
    let mut steps: Vec<Step> = manifest
        .lines()
        .filter_map(|l| {
            let mut f = l.split('\t');
            match (f.next()?, f.next()?, f.next()) {
                ("path", p, None) => Some(Step::Path(p.into())),
                ("line", file, Some(text)) => Some(Step::Line(file.into(), text.into())),
                ("vscode", e, None) => Some(Step::Vscode(e.into())),
                _ => None,
            }
        })
        .collect();
    if let Ok(exe) = std::env::current_exe() {
        let lib = exe.parent().map(|d| d.join("../lib/ltxp"));
        steps.push(Step::Path(exe));
        steps.extend(lib.and_then(|l| l.canonicalize().ok()).map(Step::Path));
    }
    if manifest.is_empty() {
        steps.extend(unrecorded_edits());
    }
    steps.push(Step::Path(data));
    // Copies an older installer put into Neovim's own package directory.
    steps.push(Step::Path(home().join(".local/share/nvim/site/pack/ltxp")));
    let mut seen = std::collections::HashSet::new();
    steps.retain(|s| match s {
        Step::Path(p) => p.exists() && seen.insert(p.clone()),
        Step::Line(f, l) => std::fs::read_to_string(f).is_ok_and(|t| t.lines().any(|x| x == l)),
        Step::Vscode(e) => seen.insert(PathBuf::from(e)),
    });
    steps
}

/// Edits by installers from before the manifest: generated lazy.nvim specs under the Neovim
/// config, the Emacs loader line in the usual init files, and the VS Code/VSCodium extension.
fn unrecorded_edits() -> Vec<Step> {
    let config =
        std::env::var_os("XDG_CONFIG_HOME").map_or_else(|| home().join(".config"), PathBuf::from);
    let mut out = vec![];
    let mut stack = vec![(config.join("nvim/lua"), 0)];
    while let Some((dir, depth)) = stack.pop() {
        for e in std::fs::read_dir(&dir).into_iter().flatten().flatten() {
            let p = e.path();
            if p.is_dir() && depth < 3 {
                stack.push((p, depth + 1));
            } else if p.file_name().is_some_and(|n| n == "ltxp.lua")
                && std::fs::read_to_string(&p).is_ok_and(|t| t.starts_with(SPEC_HEADER))
            {
                out.push(Step::Path(p));
            }
        }
    }
    let inits = [".emacs.d/init.el", ".emacs.el", ".emacs"].map(|f| home().join(f));
    for init in inits.into_iter().chain([config.join("emacs/init.el")]) {
        let text = std::fs::read_to_string(&init).unwrap_or_default();
        for l in text
            .lines()
            .filter(|l| l.starts_with("(load ") && l.contains("ltxp/emacs/setup.el"))
        {
            out.push(Step::Line(init.clone(), l.to_string()));
        }
    }
    for editor in ["code", "codium"] {
        let listed = Command::new(editor).arg("--list-extensions").output();
        if listed.is_ok_and(|o| {
            String::from_utf8_lossy(&o.stdout)
                .lines()
                .any(|l| l == "sichanghe.ltxp")
        }) {
            out.push(Step::Vscode(editor.into()));
        }
    }
    out
}

fn run(step: &Step) -> Result<(), String> {
    match step {
        Step::Path(p) if p.is_dir() => std::fs::remove_dir_all(p).map_err(|e| e.to_string()),
        Step::Path(p) => {
            // A lazy.nvim spec the user has since rewritten is theirs; keep it.
            let generated = std::fs::read_to_string(p).is_ok_and(|t| t.starts_with(SPEC_HEADER));
            if p.extension().is_some_and(|e| e == "lua") && !generated {
                return Err("not generated by the installer anymore; left in place".into());
            }
            std::fs::remove_file(p).map_err(|e| e.to_string())
        }
        Step::Line(f, l) => {
            let text = std::fs::read_to_string(f).map_err(|e| e.to_string())?;
            // Also drop the blank line the installer put before it.
            let mut kept: Vec<&str> = vec![];
            for x in text.lines() {
                if x == l {
                    if kept.last() == Some(&"") {
                        kept.pop();
                    }
                } else {
                    kept.push(x);
                }
            }
            std::fs::write(f, kept.join("\n") + "\n").map_err(|e| e.to_string())
        }
        Step::Vscode(e) => {
            let ok = Command::new(e)
                .args(["--uninstall-extension", "sichanghe.ltxp"])
                .output();
            match ok {
                Ok(o) if o.status.success() => Ok(()),
                Ok(o) => Err(String::from_utf8_lossy(&o.stderr).trim().to_string()),
                Err(err) => Err(format!("cannot run {e}: {err}")),
            }
        }
    }
}

/// Shows what will be removed, asks unless `yes`, then removes it. Returns the exit code.
pub fn uninstall(yes: bool) -> i32 {
    let steps = steps();
    if steps.is_empty() {
        println!("ltxp: nothing to remove");
        return 0;
    }
    println!("ltxp uninstall will:");
    for s in &steps {
        println!("  {}", describe(s));
    }
    if !yes {
        if !std::io::stdin().is_terminal() {
            eprintln!("ltxp: not a terminal; rerun with --yes to confirm");
            return 1;
        }
        print!("Proceed? [y/N] ");
        let _ = std::io::stdout().flush();
        let mut answer = String::new();
        let _ = std::io::stdin().lock().read_line(&mut answer);
        if !answer.trim().eq_ignore_ascii_case("y") {
            println!("ltxp: nothing removed");
            return 1;
        }
    }
    let mut code = 0;
    for s in &steps {
        if let Err(e) = run(s) {
            eprintln!("ltxp: could not {}: {e}", describe(s));
            code = 1;
        }
    }
    println!("ltxp: removed. Restart your editors.");
    code
}
